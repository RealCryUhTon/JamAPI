//--> GENERATED BY AI / edited to take in raw data
class Button {
  constructor(x, y, w, h, label, onClickAction, rawData) {
    this.x = x;
    this.y = y;
    this.w = w;
    this.h = h;
    this.label = label;
    this.onClickAction = onClickAction;
    this.raw = rawData;

    this.baseColor = color(240);
    this.hoverColor = color(200);
    this.textColor = color(0);
  }

  display() {
    let isHovered = this.isMouseOver();
    
    fill(isHovered ? this.hoverColor : this.baseColor);
    
    stroke(0);
    strokeWeight(1);
    rectMode(CENTER);
    rect(this.x, this.y, this.w, this.h, 5);

    noStroke();
    fill(this.textColor);
    textAlign(CENTER, CENTER);
    textSize(16);
    text(this.label, this.x, this.y);
  }

  isMouseOver() {
    let sY = this.y + scrollOffset;
    return (
      mouseX > this.x - this.w / 2 &&
      mouseX < this.x + this.w / 2 &&
      mouseY > sY - this.h / 2 &&
      mouseY < sY + this.h / 2
    );
  }

  checkClick() {
    if (this.isMouseOver() && this.onClickAction) {
      this.onClickAction();

      selectedGame = this.raw
    }
  }
}
